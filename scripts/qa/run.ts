  await shot("10c-sparkle");
  await page.eval(`(() => { const i = document.querySelector('input[name=password]'); i.value = ${JSON.stringify(sparkle.seed)}; i.dispatchEvent(new Event('input', { bubbles: true })); })()`);
  await page.clickText("Store in the hub");
  await page.waitFor("document.body.textContent.includes('All stored')", 15000);
  await shot("10d-sparkle-stored");
  listAims(fake);
  await page.clickText("Your projects", ".route button");
  await page.waitFor("document.body.textContent.includes('Install the App')", 20000);
  await shot("10e-your-projects");
  await audit("your-projects");
  await page.clickText("Projects", "nav a");
  await page.waitFor("document.body.textContent.includes('Ready to add') && document.body.textContent.includes('In the hub')", 20000);
  await shot("11-projects");
  await page.clickText("octo/aims", ".item button.link");
  await page.waitFor("document.body.textContent.includes('Where aims stands')", 20000);
  await Bun.sleep(300);
  await shot("11b-aims");
  await audit("aims-sheet");
  await page.clickText("Install the App on aims", ".sheet a");
  await page.waitFor("document.body.textContent.includes('come back to this page') || document.body.textContent.includes('The hub checks its App now')");
  fake.installation = { id: 9, repos: ["octo/ebb", "octo/aims"] };
  if (!(await page.eval<boolean>("document.body.textContent.includes('The hub checks its App now')"))) await page.clickText("Check again", ".sheet button");
  await page.waitFor("document.body.textContent.includes('reaches octo/aims; tapster checked with the App')", 30000);
  fake.appKeyWorks = false;
  fake.installation = { id: 9, repos: ["octo/ebb"] };
  await page.clickText("Refresh", ".sheet button");
  await page.waitFor("document.body.textContent.includes('could not reach octo/aims') || document.body.textContent.includes('has not checked it yet')", 15000);
  fake.installation = { id: 9, repos: ["octo/ebb", "octo/aims"] };
  await page.clickText("Check again", ".sheet button");
  await page.waitFor("document.body.textContent.includes('The hub checks its App now')");
