import { isMap, parseDocument } from "yaml";
import script from "../../dist/auto-release.js" with { type: "text" };
import pins from "../../templates/pins.json";
import { TapsterError } from "../errors";

export type AutoMode = "daily" | "push" | "off";
export const AUTO_FILE = ".github/workflows/tapster-auto.yml";
const MARKER = "# Generated by tapster: automatic releases (v1).";

export function autoMode(text: string | null): AutoMode | null {
  if (!text?.startsWith(MARKER)) return null;
  try {
    const on = (parseDocument(text).toJS() as { on?: Record<string, unknown> }).on;
    return on && "schedule" in on ? "daily" : on && "push" in on ? "push" : on && "workflow_dispatch" in on ? "off" : null;
  } catch { return null; }
}

export function autoWorkflow(mode: AutoMode, branch: string): string {
  if (!branch || /[\r\n\0]/.test(branch) || branch.includes("${{")) throw new TapsterError("the default branch is missing or invalid", "Check the repository's default branch on GitHub.");
  if (mode === "off") return `${MARKER}\nname: tapster auto\non:\n  workflow_dispatch:\npermissions: {}\njobs:\n  disabled:\n    if: false\n    runs-on: ubuntu-24.04\n    steps:\n      - run: echo "Automatic releases are disabled."\n`;
  const run = (mode: "plan" | "tag") => `          node --input-type=module - ${mode} <<'TAPSTER_AUTO'\n${script.trimEnd().split("\n").map((line) => `          ${line}`).join("\n")}\n          TAPSTER_AUTO`;
  return `${MARKER}
name: tapster auto
on:
${mode === "daily" ? '  schedule:\n    - cron: "23 3 * * *"\n' : mode === "push" ? `  push:\n    branches: [${JSON.stringify(branch)}]\n` : ""}  workflow_dispatch:
permissions: {}
concurrency:
  group: tapster-auto
  cancel-in-progress: false
jobs:
  plan:
    if: \${{ github.ref == format('refs/heads/{0}', github.event.repository.default_branch) }}
    runs-on: ubuntu-24.04
    timeout-minutes: 10
    permissions: { contents: read }
    outputs:
      tag: \${{ steps.plan.outputs.tag }}
      sha: \${{ steps.plan.outputs.sha }}
      refs: \${{ steps.plan.outputs.refs }}
    steps:
      - uses: actions/checkout@${pins["actions/checkout"].sha} # ${pins["actions/checkout"].tag}
        with:
          ref: \${{ github.event.repository.default_branch }}
          fetch-depth: 0
          persist-credentials: false
      - name: Analyze changes since the highest version tag
        id: plan
        env: { GH_TOKEN: "\${{ github.token }}" }
        run: |
${run("plan")}
  tag:
    needs: plan
    if: \${{ needs.plan.outputs.tag != '' && github.ref == format('refs/heads/{0}', github.event.repository.default_branch) }}
    runs-on: ubuntu-24.04
    timeout-minutes: 5
    environment: release
    permissions: { contents: read }
    steps:
      - uses: actions/checkout@${pins["actions/checkout"].sha} # ${pins["actions/checkout"].tag}
        with:
          ref: \${{ needs.plan.outputs.sha }}
          ssh-key: \${{ secrets.TAPSTER_TAG_KEY }}
          persist-credentials: true
      - name: Recheck the branch and tags, then push one tag
        env:
          GH_TOKEN: \${{ github.token }}
          RELEASE_TAG: \${{ needs.plan.outputs.tag }}
          RELEASE_SHA: \${{ needs.plan.outputs.sha }}
          RELEASE_REFS: \${{ needs.plan.outputs.refs }}
        run: |
${run("tag")}
`;
}

// An automatic tag must start a build. Fail before setup rather than quietly producing tags the workflow ignores.
export function checkAutoReleaseWorkflow(text: string): void {
  const doc = parseDocument(text);
  const on = doc.get("on");
  const push = isMap(on) ? on.get("push") : null;
  const tags = isMap(push) ? push.get("tags") : null;
  const patterns: unknown = tags && typeof tags === "object" && "toJSON" in tags ? (tags as { toJSON(): unknown }).toJSON() : null;
  if (!Array.isArray(patterns) || !patterns.some((p) => p === "v*" || p === "v[0-9]+.[0-9]+.[0-9]+")) {
    throw new TapsterError("the release workflow does not explicitly build vMAJOR.MINOR.PATCH tags", 'Use push.tags: ["v*"] in the release workflow before enabling --auto.');
  }
  if (isMap(push) && ["branches", "branches-ignore", "paths", "paths-ignore", "tags-ignore"].some((k) => push.has(k))) {
    throw new TapsterError("the release workflow has push filters besides version tags", "Keep its push trigger for version tags only; automatic tagging has its own workflow.");
  }
}
